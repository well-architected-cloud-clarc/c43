#!/usr/bin/env python3
"""Generate src/drawio/elms_metrics.rs: advance widths (per mille of the em) of printable ASCII for the vendored Elms Sans files.
Usage: scripts/font_metrics.py   (needs python fontTools + brotli)"""
import os
from fontTools.ttLib import TTFont

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
faces = [("THIN", "elms-sans-latin-100-normal.woff2"), ("NAME", "elms-sans-latin-400-normal.woff2")]
out = ["//! Generated by scripts/font_metrics.py from media/fonts: advance widths in 1/1000 em, printable ASCII from the space on.", ""]
for const, file in faces:
    f = TTFont(os.path.join(root, "media/fonts", file))
    cmap, hmtx, upm = f.getBestCmap(), f["hmtx"], f["head"].unitsPerEm
    w = [round(hmtx[cmap[c]][0] * 1000 / upm) for c in range(32, 127)]
    out += [f"pub const {const}: [u16; {len(w)}] = {w};".replace("[", "[", 1), ""]
open(os.path.join(root, "src/drawio/elms_metrics.rs"), "w").write("\n".join(out))
